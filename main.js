function getValue(t, key) {
  // Direct flat key lookup (keys contain literal dots, e.g. "nav.home")
  return t[key] !== undefined ? t[key] : null;
}

function applyLanguage(lang) {
  const t = translations[lang];
  if (!t) return;

  // RTL support for Arabic
  const isRTL = lang === 'ar';
  document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;

  // Apply text translations
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const value = getValue(t, key);
    if (value !== null) el.textContent = value;
  });

  // Apply HTML translations (for hero title with spans)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    const value = getValue(t, key);
    if (value !== null) el.innerHTML = value;
  });

  // Apply placeholder translations
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const value = getValue(t, key);
    if (value !== null) el.placeholder = value;
  });

  // Update active lang button + ARIA
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
  });

  // Announce language change to screen readers
  const announcement = document.getElementById('lang-announcement');
  if (announcement) {
    const langNames = { fr: 'Français', de: 'Deutsch', en: 'English', ar: 'العربية', zh: '中文' };
    announcement.textContent = `Langue : ${langNames[lang] || lang}`;
  }

  // Font override for Arabic & Chinese
  document.body.classList.remove('font-arabic', 'font-chinese');
  if (lang === 'ar') document.body.classList.add('font-arabic');
  if (lang === 'zh') document.body.classList.add('font-chinese');

  // Clear validation errors dynamically on language switch
  ['name', 'email', 'message'].forEach(fieldId => {
    const el = document.getElementById('error-' + fieldId);
    if (el) { el.textContent = ''; el.style.display = 'none'; }
    const input = document.getElementById('form-' + fieldId);
    if (input) input.classList.remove('field-invalid');
  });

  // Save preference
  localStorage.setItem('dpb-lang', lang);
}

