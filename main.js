// DOM Ready
// ============================================================

document.addEventListener('DOMContentLoaded', () => {
  console.log("Deutsch Pro Bamako — Site initialisé ✅");

  // ── Language Init ──────────────────────────────────────────
  const savedLang = localStorage.getItem('dpb-lang');
  const browserLang = navigator.language.slice(0, 2);
  const supportedLangs = Object.keys(translations);
  const initLang = supportedLangs.includes(savedLang)
    ? savedLang
    : supportedLangs.includes(browserLang)
    ? browserLang
    : 'fr';

  applyLanguage(initLang);

  // ── Language Switcher ──────────────────────────────────────
  document.getElementById('lang-switcher').addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn) applyLanguage(btn.dataset.lang);
  });

  // ── Smooth Scrolling (offset: topbar 36px + navbar 56px) ──
  const SCROLL_OFFSET = 95;
  document.querySelectorAll('.nav-link').forEach(link => {
    link.addEventListener('click', function (e) {
      e.preventDefault();
      const targetId = this.getAttribute('href').substring(1);
      const target = document.getElementById(targetId);
      if (target) {
        window.scrollTo({ top: target.offsetTop - SCROLL_OFFSET, behavior: 'smooth' });
      }
    });
  });

  // ── Secure Form — Validation & WhatsApp Submission ────────
  const form = document.getElementById('contact-form');
  if (form) {
    const currentLang = () => localStorage.getItem('dpb-lang') || 'fr';

    const validationMessages = {
      fr: { name: 'Veuillez entrer votre nom (min. 2 caractères).', email: 'Veuillez entrer une adresse email valide.', message: 'Votre message doit contenir au moins 10 caractères.', success: '✅ Message envoyé ! Nous vous répondrons bientôt via WhatsApp.', sending: 'Envoi en cours...' },
      de: { name: 'Bitte geben Sie Ihren Namen ein (mind. 2 Zeichen).', email: 'Bitte geben Sie eine gültige E-Mail-Adresse ein.', message: 'Ihre Nachricht muss mindestens 10 Zeichen lang sein.', success: '✅ Nachricht gesendet! Wir antworten Ihnen bald über WhatsApp.', sending: 'Wird gesendet...' },
      en: { name: 'Please enter your name (min. 2 characters).', email: 'Please enter a valid email address.', message: 'Your message must be at least 10 characters long.', success: '✅ Message sent! We will reply to you soon via WhatsApp.', sending: 'Sending...' },
      ar: { name: 'يرجى إدخال اسمك (٢ أحرف على الأقل).', email: 'يرجى إدخال بريد إلكتروني صحيح.', message: 'يجب أن تحتوي رسالتك على ١٠ أحرف على الأقل.', success: '✅ تم إرسال الرسالة! سنرد عليك قريباً عبر واتساب.', sending: 'جارٍ الإرسال...' },
      zh: { name: '请输入您的姓名（至少2个字符）。', email: '请输入有效的电子邮件地址。', message: '您的消息至少需要10个字符。', success: '✅ 消息已发送！我们将很快通过WhatsApp回复您。', sending: '正在发送...' }
    };

    function showError(fieldId, msg) {
      const el = document.getElementById('error-' + fieldId);
      if (el) { el.textContent = msg; el.style.display = 'block'; }
      const input = document.getElementById('form-' + fieldId);
      if (input) input.classList.add('field-invalid');
    }

    function clearError(fieldId) {
      const el = document.getElementById('error-' + fieldId);
      if (el) { el.textContent = ''; el.style.display = 'none'; }
      const input = document.getElementById('form-' + fieldId);
      if (input) input.classList.remove('field-invalid');
    }

    function sanitize(str) {
      // Remove HTML tags and limit length
      return str.replace(/<[^>]*>/g, '').trim().substring(0, 1000);
    }

    form.addEventListener('submit', (e) => {
      e.preventDefault();

      // ── Honeypot check (bot detection) ──
      const honeypot = form.querySelector('[name="_honeypot"]');
      if (honeypot && honeypot.value.trim() !== '') {
        console.warn('Bot détecté — soumission bloquée.');
        return;
      }

      const lang = currentLang();
      const msgs = validationMessages[lang] || validationMessages.fr;
      let valid = true;

      // Clear errors
      ['name', 'email', 'message'].forEach(clearError);

      // Validate name
      const name = sanitize(document.getElementById('form-name')?.value || '');
      if (name.length < 2) { showError('name', msgs.name); valid = false; }

      // Validate email
      const email = sanitize(document.getElementById('form-email')?.value || '');
      const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
      if (!emailRegex.test(email)) { showError('email', msgs.email); valid = false; }

      // Validate message
      const message = sanitize(document.getElementById('form-message')?.value || '');
      if (message.length < 10) { showError('message', msgs.message); valid = false; }

      if (!valid) return;

      // ── Submit via WhatsApp (pre-filled message) ──
      const phone = sanitize(document.getElementById('form-phone')?.value || '');
      const waText = encodeURIComponent(
        `🎓 *Nouveau message — Deutsch Pro Bamako*\n\n` +
        `👤 *Nom :* ${name}\n` +
        `📧 *Email :* ${email}\n` +
        (phone ? `📞 *Tél :* ${phone}\n` : '') +
        `\n💬 *Message :*\n${message}`
      );

      const submitBtn = document.getElementById('form-submit-btn');
      submitBtn.textContent = msgs.sending;
      submitBtn.disabled = true;

      setTimeout(() => {
        window.open(`https://wa.me/22379875654?text=${waText}`, '_blank', 'noopener,noreferrer');

        const successEl = document.getElementById('form-success');
        if (successEl) {
          successEl.textContent = msgs.success;
          successEl.style.display = 'block';
        }

        form.reset();
        submitBtn.disabled = false;
        const t = translations[lang];
        if (t) submitBtn.textContent = t['contact.form.submit'] || 'Envoyer le message';
      }, 600);
    });

    // Live validation on blur
    ['name', 'email', 'message'].forEach(field => {
      const input = document.getElementById('form-' + field);
      if (input) {
        input.addEventListener('blur', () => {
          const lang = currentLang();
          const msgs = validationMessages[lang] || validationMessages.fr;
          if (field === 'name' && input.value.trim().length >= 2) clearError('name');
          if (field === 'email') {
            const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
            if (emailRegex.test(input.value)) clearError('email');
          }
          if (field === 'message' && input.value.trim().length >= 10) clearError('message');
        });
      }
    });
  }

  // ── Scroll-reveal animation for cards ─────────────────────
  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.style.opacity = '1';
        entry.target.style.transform = 'translateY(0)';
        obs.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });

  document.querySelectorAll('.contact-card').forEach(card => {
    card.style.opacity = '0';
    card.style.transform = 'translateY(30px)';
    card.style.transition = 'all 0.6s ease-out';
    observer.observe(card);
  });

  // ── Navbar scroll effect ───────────────────────────────────
  window.addEventListener('scroll', () => {
    const navbar = document.querySelector('.navbar');
    navbar.classList.toggle('scrolled', window.scrollY > 50);
  });
});
